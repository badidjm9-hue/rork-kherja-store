    fun string(key: String, lang: String): String =
        (if (lang == "ar") ar[key] else null) ?: fr[key] ?: key

    /** Maps server exception messages to localized keys. */
    fun serverErrorKey(message: String?): String {
        val m = (message ?: "").lowercase()
        return when {
            "vehicle suspended" in m -> "err_vehicle_suspended"
            "too many saved" in m || "too many vehicles" in m -> "err_limit_reached"
            "uq_" in m || "duplicate key" in m -> "err_duplicate"
            "phone_not_verified" in m -> "err_phone_required"
            "sos_rate_limit" in m -> "sos_rate_limit"
            "active request" in m -> "err_active_request"
            "active ride" in m -> "err_active_ride"
            "out of allowed range" in m -> "err_fare_range"
            "no longer available" in m || "not found" in m -> "err_unavailable"
            "finish your current ride" in m -> "err_finish_ride"
            "suspended" in m -> "err_suspended"
            "not approved" in m -> "err_not_approved"
            "distance out of range" in m -> "err_distance"
            else -> "error_generic"
        }
    }
