    /// Maps server exception messages to localized, user-facing text.
    static func serverErrorKey(_ message: String) -> String {
        let m = message.lowercased()
        if m.contains("active request") { return "err_active_request" }
        if m.contains("active ride") { return "err_active_ride" }
        if m.contains("out of allowed range") { return "err_fare_range" }
        if m.contains("no longer available") || m.contains("not found") { return "err_unavailable" }
        if m.contains("finish your current ride") { return "err_finish_ride" }
        if m.contains("suspended") { return "err_suspended" }
        if m.contains("not approved") { return "err_not_approved" }
        if m.contains("distance out of range") { return "err_distance" }
        return "error_generic"
    }

    static func string(_ key: String, _ lang: AppLanguage) -> String {
        let dict = lang == .ar ? ar : fr
        return dict[key] ?? fr[key] ?? key
    }
